"""Figure 4 — component-based annual generation with evidence tiers. The 12-month cycle is the bottom-up components
driven by real annual weather; only Oct-Feb is LV-validated, Mar-May is heating interpolation, Jun-Sep is a cooling-prior
scenario (band). Figure marks validated / inferred / scenario explicitly.

Ported verbatim (numerics unchanged) from the source `configured asset`. Reads scorecards + frozen closure surface.
"""

from wlpr.io.bindings import asset as _asset_location
import os
import numpy as np, pandas as pd, duckdb
import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
from matplotlib.gridspec import GridSpec
from matplotlib.patches import Patch
from wlpr.io.paths import input_path, out_path

MNAME = ['', 'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
TIERCOL = {1: '#2e8b57', 2: '#d8a200', 3: '#c0653a'}   # validated / heating-interp / cooling-scenario
TIERBG = {1: '#e9f5ee', 2: '#fbf3df', 3: '#f8ece4'}


def build_annual_figure():
    sysG = pd.read_csv(out_path(_asset_location('asset_0058'), "annual_generation_system.csv")).sort_values('month')
    G = pd.read_csv(out_path(_asset_location('asset_0058'), "annual_generation_by_pref.csv"))
    # observed validated-month system mean-daily total (truth overlay) from frozen closure surface
    SH = input_path("closure_surface_share").replace("\\", "/")
    con = duckdb.connect(); con.execute("SET memory_limit='6GB'"); con.execute("SET preserve_insertion_order=false")
    obs = con.execute(f"select substr(d,1,6) ym, sum(obs)/count(distinct d) o from '{SH}' group by 1").df()
    obs['mo'] = obs.ym.str[4:6].astype(int)
    obs_by_mo = obs.groupby('mo').o.mean()   # mean daily total per calendar month (validated window)

    plt.rcParams.update({'font.size': 9.5, 'axes.grid': True, 'grid.alpha': 0.25, 'axes.titlesize': 10.5, 'axes.titleweight': 'bold'})
    fig = plt.figure(figsize=(16, 9)); gs = GridSpec(2, 2, figure=fig, height_ratios=[1.25, 1], hspace=0.32, wspace=0.22)

    # A annual monthly load with tier backgrounds + cooling band + observed overlay
    ax = fig.add_subplot(gs[0, :])
    m = sysG.month.values; c = sysG.central_mwh.values
    for mo, t in zip(sysG.month, sysG.tier):
        ax.axvspan(mo-0.5, mo+0.5, color=TIERBG[t], zorder=0)
    # cooling scenario band
    summer = sysG[sysG.tier == 3]
    ax.fill_between(summer.month, summer.lo_mwh, summer.hi_mwh, color=TIERCOL[3], alpha=0.25, label='cooling scenario band (low–high)')
    for t in (1, 2, 3):
        s = sysG[sysG.tier == t]
        ax.plot(s.month, s.central_mwh, '-o', color=TIERCOL[t], lw=2, ms=5, label=f'twin: {s.tier_label.iloc[0]}')
    # observed truth overlay (validated months only)
    ov = [(mo, obs_by_mo[mo]) for mo in sysG[sysG.tier == 1].month if mo in obs_by_mo.index]
    if ov:
        ax.scatter([x[0] for x in ov], [x[1] for x in ov], s=70, facecolor='none', edgecolor='k', lw=1.6, zorder=5, label='observed (validated)')
    ax.set_xticks(range(1, 13)); ax.set_xticklabels(MNAME[1:]); ax.set_ylabel('mean daily load (MWh/day)')
    ax.set_title('A  Component-based annual generation — bottom-up components driven by real weather, by evidence tier')
    ax.legend(fontsize=8, ncol=2, loc='upper center')

    # B stacked component channels by month (the bottom-up composition through the year)
    ax = fig.add_subplot(gs[1, 0])
    comp = G.groupby('month', as_index=False)[['base_mwh', 'hvac_mwh']].sum().sort_values('month')
    # cooling central per month (only summer non-zero)
    cool = sysG.assign(cool=lambda x: np.where(x.tier == 3, x.central_mwh - x.base_mwh - x.hvac_mwh, 0)).groupby('month').cool.sum()
    base = comp.base_mwh.values; hv = comp.hvac_mwh.values; co = cool.reindex(comp.month).fillna(0).values
    ax.bar(comp.month, base, color='#4C72B0', label='non-thermal + WFH (base)')
    ax.bar(comp.month, hv, bottom=base, color='#C44E52', label='HVAC heating')
    ax.bar(comp.month, co, bottom=base+hv, color='#55A1C8', label='cooling (scenario)')
    ax.set_xticks(range(1, 13)); ax.set_xticklabels(MNAME[1:]); ax.set_ylabel('MWh/day'); ax.set_title('B  Component composition by month (bottom-up)')
    ax.legend(fontsize=8)

    # C evidence-tier legend + honest statement
    ax = fig.add_subplot(gs[1, 1]); ax.axis('off')
    handles = [Patch(facecolor=TIERBG[t], edgecolor=TIERCOL[t], label=lab) for t, lab in
               [(1, 'Oct–Feb: observed-VALIDATED (LV)'), (2, 'Mar–May: heating INTERPOLATION (no LV)'),
                (3, 'Jun–Sep: cooling SCENARIO (CDD prior, no LV)')]]
    ax.legend(handles=handles, fontsize=10, loc='upper left', frameon=True, title='Evidence tiers', title_fontsize=11)
    ax.text(0.0, 0.45,
            "• Generated by the SAME bottom-up components\n"
            "  (HVAC / cooling / non-thermal / WFH per 500 m mesh),\n"
            "  driven by real frozen multi-year AMeDAS weather.\n"
            "• Cooling channel is unidentified by winter data (CDD≈0\n"
            "  in Oct–Feb) → summer is a CDD-prior band, expressed\n"
            "  through the component cooling channel, not a\n"
            "  black-box regression.\n"
            "• Summer carries NO LV validation; band = low/central/high\n"
            "  cooling sensitivity. PV stays scenario-only (never in load).",
            va='top', ha='left', fontsize=9.2, family='monospace',
            bbox=dict(boxstyle='round', fc='#f4f6fa', ec='#3b6db5'))

    fig.suptitle('Figure 4 — Annual generation with evidence tiers (component-based, weather-driven)', fontsize=13.5, fontweight='bold', y=0.99)
    plt.tight_layout(); plt.savefig(out_path(_asset_location('asset_0059'), "fig4_annual_evidence_tiers.png"), dpi=150, bbox_inches='tight')
    plt.savefig(out_path(_asset_location('asset_0059'), "fig4_annual_evidence_tiers.pdf"), bbox_inches='tight'); plt.close()
    return dict(months=len(sysG))


def main():
    return build_annual_figure()


if __name__ == "__main__":
    main()
