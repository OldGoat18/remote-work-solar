"""BMS-CAL step 4 — component-based annual generation with EVIDENCE TIERS (bottom-up forward simulation, NOT a top-down
HDD regression).

Ported verbatim (numerics unchanged) from the source `configured asset`.

The annual cycle is generated by driving the SAME bottom-up component channels with annual weather:
  load(g,d,slot) = HVAC_n(g)·a_hvac(pref,weather) + HVAC_n(g)·a_cool(pref,weather)
                 + person_n(g)·a_nonth(pref) + wfh_n(g)·a_wfh(pref)
where the per-mesh census channel weights {HVAC_n, person_n, wfh_n} are the non-circular census denominators (constant),
and the per-channel daily shapes a_* come from the SAME mechanism fit on the validated Oct-Feb load, evaluated on annual
weather. Because aggregation is linear, the pref/system monthly energy = Σ_g(weight_n) · a_channel — a pre-summed
bottom-up aggregate (each mesh's physical component summed), NOT a fitted total.

Evidence tiers:
  Oct-Feb  validated (the component channels are LV-closed in this window)
  Mar-May  heating interpolation — component HVAC channel driven by spring HDD (in-range; no LV validation)
  Jun-Sep  cooling scenario — the component COOLING channel is unidentified by winter data (CDD≈0 in Oct-Feb), so it is
           driven by a CDD prior (low/central/high). This is exactly why summer is scenario-only, expressed through the
           component cooling channel rather than a black-box.
PV stays scenario-only and never enters this load generation.
"""

from wlpr.io.bindings import asset as _asset_location
import os, datetime
import numpy as np, pandas as pd, duckdb
from scipy.optimize import nnls
from wlpr.io.paths import input_path, out_path, model_config

STN = {'11': '埼玉熊谷', '12': '千葉', '13': '東京', '14': '神奈川横浜'}
PN = {'11': 'Saitama', '12': 'Chiba', '13': 'Tokyo', '14': 'Kanagawa'}
GENYEAR = '2024'
TIER = {1: 'validated (Oct-Feb)', 2: 'heating interpolation (Mar-May)', 3: 'cooling scenario (Jun-Sep)'}
COOL_FRAC = {'low': 0.35, 'central': 0.6, 'high': 0.9}   # summer AC sensitivity as a fraction of the heating slope (prior)
HOL = {'20231009', '20231103', '20231123', '20231229', '20231230', '20231231',
       '20240101', '20240102', '20240103', '20240108', '20240211', '20240212', '20240223'}


def _con():
    tmp = out_path(_asset_location('asset_0085'), _asset_location('asset_0145')); os.makedirs(tmp, exist_ok=True)
    c = duckdb.connect(); c.execute("SET memory_limit='10GB'"); c.execute("SET threads=6")
    c.execute(f"SET temp_directory='{tmp}'"); c.execute("SET preserve_insertion_order=false")
    return c


def run_annual_generation():
    cfg = model_config(); W_OWN = {k: float(v) for k, v in cfg['weather']['pop_weight_own_station'].items()}
    hb, cb = float(cfg['weather']['hdd_base_c']), float(cfg['weather']['cdd_base_c'])
    NB = int(cfg['agent_prior']['env_bumps']); TAU = float(cfg['agent_prior']['pooling_tau'])
    AME = input_path("weather_amedas").replace("\\", "/")
    STD = input_path("lv_load_hourly").replace("\\", "/")
    MESH = input_path("mesh_denominator_panel")
    HOUS = input_path("census_housing_T001194")
    DEMO = input_path("demographic_mesh_panel")
    SHP = input_path("closure_surface_share").replace("\\", "/")
    con = _con()

    # ---- per-mesh census channel weights (same as the component build), summed per pref over load-bearing meshes ----
    HJ = con.execute(f"""select mesh, pref_code pref, T001194001 hh, T001194002 own_hh, T001194007 detached,
        T001194008 rowhouse, T001194009 apartment from '{HOUS.replace(chr(92),'/')}'""").df(); HJ['pref'] = HJ.pref.astype(str)
    for c_ in ['hh', 'own_hh', 'detached', 'rowhouse', 'apartment']:
        HJ[c_] = pd.to_numeric(HJ[c_], errors='coerce')
    HL_D = float(cfg['heat_loss']['HL_detached']); HL_R = float(cfg['heat_loss']['HL_rowhouse'])
    HJ['det_sh'] = HJ.detached/HJ.hh; HJ['row_sh'] = HJ.rowhouse/HJ.hh; HJ['apt_sh'] = HJ.apartment/HJ.hh
    HJ['heatloss'] = HJ.det_sh*HL_D + HJ.row_sh*HL_R + HJ.apt_sh*1.0
    DM = pd.read_parquet(DEMO)[['mesh', 'mean_hh_size', 'wage_share']]
    H = HJ.merge(DM, on='mesh', how='left')
    for col in ['heatloss', 'mean_hh_size', 'wage_share']:
        H[col] = H[col].fillna(H.pref.map(H.groupby('pref')[col].mean()))
    H['hh'] = H.hh.fillna(H.pref.map(H.groupby('pref').hh.mean()))
    H['w_hvac'] = H.hh*H.heatloss; H['w_nth'] = H.hh*H.mean_hh_size; H['w_wfh'] = H.hh*H.wage_share
    for ch in ['w_hvac', 'w_nth', 'w_wfh']:
        H[ch+'_n'] = H[ch]/H.pref.map(H.groupby('pref')[ch].mean())
    Hn = H[['mesh', 'w_hvac_n', 'w_nth_n', 'w_wfh_n']].rename(columns={'w_hvac_n': 'HVAC_n', 'w_nth_n': 'person_n', 'w_wfh_n': 'wfh_n'})
    GR = con.execute(f"select distinct cast(g as varchar) mesh, cast(pref as varchar) pref from '{SHP}'").df()
    Mden = GR.merge(Hn, on='mesh', how='left')
    for c in ['HVAC_n', 'person_n', 'wfh_n']:
        Mden[c] = Mden[c].fillna(1.0)
    Wn = Mden.groupby('pref')[['HVAC_n', 'person_n', 'wfh_n']].sum()   # Σ_g weight_n(g) per pref (bottom-up aggregate)

    # ---- census mechanism denominators (per pref) ----
    MM = pd.read_parquet(MESH)[['mesh', 'pref', 'conditioned_dwelling', 'person', 'wfh_eligible']]; MM['pref'] = MM.pref.astype(str)
    pdg = MM.groupby('pref')[['conditioned_dwelling', 'person', 'wfh_eligible']].sum(); nrm = {c: pdg[c].mean() for c in pdg.columns}
    DEN_P = {p: {'HVAC': pdg.loc[p, 'conditioned_dwelling']/nrm['conditioned_dwelling'], 'person': pdg.loc[p, 'person']/nrm['person'],
                 'wfh': pdg.loc[p, 'wfh_eligible']/nrm['wfh_eligible']} for p in STN}

    # ---- weather: 48-slot temp per (pref,day) for ALL available days ----
    daily = {}
    for s in set(STN.values()) | {'東京'}:
        t = con.execute(f"""select strftime(cast(timestamp+INTERVAL 9 HOUR as DATE),'%Y%m%d') d, hour(timestamp+INTERVAL 9 HOUR) hr, avg(temp) t
            from '{AME}' where station='{s}' group by 1,2""").df()
        for (d, ), g in t.groupby(['d']):
            hrs = g.set_index('hr').t.reindex(range(24)).interpolate().bfill().ffill().values
            daily[(s, d)] = np.interp(np.arange(48)*0.5, np.arange(24), hrs, period=24)
    def slotT(pref, d):
        s = STN[pref]
        if (s, d) in daily and ('東京', d) in daily:
            return W_OWN[pref]*daily[(s, d)] + (1-W_OWN[pref])*daily[('東京', d)]
        return None

    hod = np.arange(48)/2.0; gauss = lambda c, w: np.exp(-0.5*((hod-c)/w)**2)
    B_act = ((hod >= 9) & (hod <= 17)).astype(float)*gauss(13, 3.0); B_eve = 1/(1+np.exp(-(hod-16)))
    BUMPS = [gauss(c, 1.25) for c in np.linspace(0.5, 23.5, NB)]
    HVACN = ['HVAC', 'HVAC_eve', 'COOL']; ENVN = [f'env{k:02d}' for k in range(NB)]; CN = HVACN+['wfh']+ENVN

    def shapes(pref, d):
        T = slotT(pref, d); hdd = np.clip(hb-T, 0, None); cdd = np.clip(T-cb, 0, None)
        c = {'HVAC': hdd, 'HVAC_eve': hdd*B_eve, 'COOL': cdd, 'wfh': B_act}
        for k in range(NB):
            c[f'env{k:02d}'] = BUMPS[k]
        return c

    def Xrow(pref, d, wk):
        sh = shapes(pref, d); Dp = DEN_P[pref]; cols = []
        for n in CN:
            ch = 'HVAC' if n in HVACN else ('wfh' if n == 'wfh' else 'person'); ss = sh[n].copy()
            if wk and n == 'wfh':
                ss = np.zeros(48)
            cols.append(Dp[ch]*ss)
        return np.column_stack(cols)

    # ---- fit agent coefficients on the VALIDATED Oct-Feb load (all months, per pref, weekday/weekend) ----
    LV = "voltage='低圧' and flow='順' and pref_code in ('11','12','13','14')"
    panel = con.execute(f"select pref_code pref,date_str d,(cast(hour_str as int)-1) slot, sum(kwh)/1e3 mwh from '{STD}' where {LV} group by 1,2,3").df()
    panel['pref'] = panel.pref.astype(str)
    valwin = ['202310', '202311', '202312', '202401', '202402']
    is_wk = lambda d: datetime.date(int(d[:4]), int(d[4:6]), int(d[6:8])).weekday() >= 5 or d in HOL
    def ovf(pref, d):
        y = panel[(panel.pref == pref) & (panel.d == d)].sort_values('slot').mwh.values
        return y if len(y) == 48 else None
    NPc = len(CN); iCO = CN.index('COOL')
    coef = {}   # (pref, wk) -> bp
    for wk in (False, True):
        Xs, Ys = [], []
        for pref in STN:
            for d in [d for (s, d) in daily if s == STN[pref] and d[:6] in valwin]:
                if is_wk(d) != wk:
                    continue
                y = ovf(pref, d);
                if y is None or slotT(pref, d) is None:
                    continue
                Xs.append(Xrow(pref, d, wk)); Ys.append(y)
        mu = nnls(np.vstack(Xs), np.concatenate(Ys))[0]
        for pref in STN:
            Xp, Yp = [], []
            for d in [d for (s, d) in daily if s == STN[pref] and d[:6] in valwin]:
                if is_wk(d) != wk:
                    continue
                y = ovf(pref, d)
                if y is None or slotT(pref, d) is None:
                    continue
                Xp.append(Xrow(pref, d, wk)); Yp.append(y)
            coef[(pref, wk)] = nnls(np.vstack([np.vstack(Xp), TAU*np.eye(NPc)]), np.concatenate([np.concatenate(Yp), TAU*mu]))[0]

    iHV = [CN.index(n) for n in ['HVAC', 'HVAC_eve']]; iE = [CN.index(n) for n in ENVN]; iW = CN.index('wfh')
    iHVm = CN.index('HVAC')   # main heating coefficient = sensitivity anchor for the cooling-scenario prior

    # ---- forward-generate every day of GENYEAR per pref, aggregate mesh weights (bottom-up), split components ----
    gen = []
    for pref in STN:
        wn = Wn.loc[pref]
        for d in sorted([d for (s, d) in daily if s == STN[pref] and d[:4] == GENYEAR]):
            if slotT(pref, d) is None:
                continue
            wk = is_wk(d); bp = coef[(pref, wk)]; sh = shapes(pref, d); Dp = DEN_P[pref]
            # per-channel agent component DAILY ENERGY (sum of slots). a_* = bp·DEN_P·shape already predicts the pref
            # total (DEN_P is the census-summed pref denominator, bp fit to pref total); the per-mesh HVAC_n/person_n/wfh_n
            # weights are the WITHIN-pref spatial distribution for the grid product, NOT a second pref-level factor.
            a_hv = sum(bp[i]*sh[CN[i]] for i in iHV) * Dp['HVAC']
            a_co = bp[iCO]*sh['COOL'] * Dp['HVAC']
            a_no = sum(bp[i]*sh[CN[i]] for i in iE) * Dp['person']
            a_wf = (bp[iW]*sh['wfh'] if not wk else np.zeros(48)) * Dp['wfh']
            E_hvac = a_hv.sum(); E_cool = a_co.sum(); E_nonth = a_no.sum(); E_wfh = a_wf.sum()
            # cooling "unit" load: what cooling would be at the HEATING sensitivity, driven by this day's CDD shape.
            # dimensionally identical to E_hvac (bp·DEN·Σshape); the scenario scales it by COOL_FRAC (AC vs heating sens).
            E_cool_unit = (bp[iHVm] * np.clip(slotT(pref, d)-cb, 0, None) * Dp['HVAC']).sum()
            gen.append(dict(pref=pref, d=d, ym=d[:6], month=int(d[4:6]),
                            E_hvac=E_hvac, E_cool_winterfit=E_cool, E_nonth=E_nonth, E_wfh=E_wfh,
                            E_cool_unit=E_cool_unit, cdd=np.clip(slotT(pref, d)-cb, 0, None).sum()))
    Gd = pd.DataFrame(gen)
    Gm = Gd.groupby(['pref', 'ym', 'month'], as_index=False)[['E_hvac', 'E_cool_winterfit', 'E_nonth', 'E_wfh', 'E_cool_unit', 'cdd']].mean()
    rows = []
    for _, r in Gm.iterrows():
        tier = 1 if r.month in (10, 11, 12, 1, 2) else (2 if r.month in (3, 4, 5) else 3)
        base = r.E_nonth + r.E_wfh
        if tier in (1, 2):
            central = base + r.E_hvac + r.E_cool_winterfit; lo = central; hi = central
        else:
            # cooling SCENARIO = COOL_FRAC × (cooling-at-heating-sensitivity), dimensionally consistent with E_hvac.
            cool = {k: COOL_FRAC[k] * r.E_cool_unit for k in COOL_FRAC}
            central = base + r.E_hvac + cool['central']; lo = base + r.E_hvac + cool['low']; hi = base + r.E_hvac + cool['high']
        rows.append(dict(pref=r.pref, ym=r.ym, month=r.month, tier=tier, tier_label=TIER[tier],
                         base_mwh=base, hvac_mwh=r.E_hvac, central_mwh=central, lo_mwh=lo, hi_mwh=hi, cdd=r.cdd))
    G = pd.DataFrame(rows)
    sysG = G.groupby(['ym', 'month', 'tier', 'tier_label'], as_index=False)[['base_mwh', 'hvac_mwh', 'central_mwh', 'lo_mwh', 'hi_mwh']].sum()
    # observed system monthly mean-daily (validated truth overlay) from closure obs
    obs = con.execute(f"select substr(d,1,6) ym, sum(obs)/count(distinct d) o from '{SHP}' group by 1").df()
    obs['mo'] = obs.ym.str[4:6].astype(int); obs_by_mo = obs.groupby('mo').o.mean()
    # validated-tier truth check (generation central vs observed mean-daily). Jan/Feb are the SAME generation year (2024)
    # as the obs; Oct/Nov/Dec compare generation-year 2024 weather against observed 2023 (cross-year) — a documented
    # tier-1 caveat (generation-year weather), NOT a model error. 09_verify_outputs gates same-year vs cross-year apart.
    SAME_YEAR = {1, 2}
    vrows = []
    for _, r in sysG[sysG.tier == 1].sort_values('month').iterrows():
        mo = int(r.month)
        if mo in obs_by_mo.index:
            o = float(obs_by_mo[mo]); g = float(r.central_mwh)
            vrows.append(dict(month=mo, ym=r.ym, gen_central_mwh=g, obs_mwh=o, rel_err=(g - o) / o,
                              same_gen_year=mo in SAME_YEAR))
    pd.DataFrame(vrows).to_csv(out_path(_asset_location('asset_0058'), "annual_validation_vs_obs.csv"), index=False)
    G.to_csv(out_path(_asset_location('asset_0058'), "annual_generation_by_pref.csv"), index=False)
    sysG.to_csv(out_path(_asset_location('asset_0058'), "annual_generation_system.csv"), index=False)
    return dict(G=G, sysG=sysG, obs=obs)


def main():
    out = run_annual_generation()
    print(f"[15] annual generation: {len(out['sysG'])} system-months (tiered validated/interp/scenario)")
    return out


if __name__ == "__main__":
    main()
